"""Render and update the pull request body (§9.4).

The agent log section is rewritten on every repair attempt, so it is delimited
by markers rather than reconstructed from scratch: anything a human adds to the
body survives.
"""

from __future__ import annotations

from typing import Final

from vulnagent.core.errors import PurlError
from vulnagent.core.models import (
    BumpDirect,
    BumpParent,
    Override,
    Severity,
    UpgradeAction,
    UpgradePlan,
)
from vulnagent.core.purl import parse_purl

LOG_START: Final = "<!-- vulnagent:log:start -->"
LOG_END: Final = "<!-- vulnagent:log:end -->"

_SEVERITY_ORDER: Final[tuple[Severity, ...]] = ("critical", "high", "medium", "low", "unknown")

_UNRESOLVED_WORDING: Final = {
    "no_fix": "no fixed version available",
    "needs_major": "the fix is a major bump, and `allow_major_bumps` is false",
    "conflict": "the fix conflicts with a version range the manifest declares",
}


def pr_title(resolved: int) -> str:
    noun = "vulnerability" if resolved == 1 else "vulnerabilities"
    return f"fix(deps): resolve {resolved} {noun}"


def commit_message(resolved: int) -> str:
    noun = "vulnerability" if resolved == 1 else "vulnerabilities"
    return f"fix(deps): resolve {resolved} {noun} [vulnagent]"


def render_pr_body(
    plan: UpgradePlan,
    *,
    severities: dict[str, Severity],
    advisory_for: dict[str, str],
    max_attempts: int,
    log_entries: list[str] | None = None,
) -> str:
    """`severities` and `advisory_for` are keyed by the purl each action fixes."""
    counts = _counts(plan, severities)
    total = len(plan.resolves)
    noun = "vulnerability" if total == 1 else "vulnerabilities"

    sections = [
        "## 🔒 VulnAgent: dependency security update",
        "",
        f"Resolves **{total}** {noun}{_breakdown(counts)}.",
        "",
        _table(plan, severities=severities, advisory_for=advisory_for),
    ]
    if plan.unresolved:
        sections += ["", "### Not fixed", _not_fixed(plan)]
    if plan.major_bumps:
        sections += [
            "",
            "### Major version bumps",
            "These cross a major version, so read the changelogs before merging:",
            "",
            *(f"- `{name}`" for name in plan.major_bumps),
        ]
    sections += [
        "",
        "### Agent log",
        LOG_START,
        _log(log_entries or []),
        LOG_END,
        "",
        f"<sub>Generated by VulnAgent. Config: `.vulnagent.yml`. "
        f"Max CI repair attempts: {max_attempts}.</sub>",
    ]
    return "\n".join(sections)


def update_agent_log(body: str, log_entries: list[str]) -> str:
    """Replace just the agent log, leaving everything else in the body alone."""
    start = body.find(LOG_START)
    end = body.find(LOG_END)
    if start == -1 or end == -1 or end < start:
        return f"{body}\n\n### Agent log\n{LOG_START}\n{_log(log_entries)}\n{LOG_END}"
    return f"{body[: start + len(LOG_START)]}\n{_log(log_entries)}\n{body[end:]}"


def _table(
    plan: UpgradePlan, *, severities: dict[str, Severity], advisory_for: dict[str, str]
) -> str:
    rows = [
        "| Advisory | Package | From → To | Severity | Type |",
        "|---|---|---|---|---|",
    ]
    for action in plan.actions:
        purl = _reason_of(action)
        rows.append(
            "| {advisory} | {package} | {change} | {severity} | {kind} |".format(
                advisory=advisory_for.get(purl, "-"),
                package=_package_label(action),
                change=_change_label(action),
                severity=severities.get(purl, "unknown"),
                kind=_kind_label(action),
            )
        )
    return "\n".join(rows)


def _package_label(action: UpgradeAction) -> str:
    match action:
        case BumpDirect(name=name) | Override(name=name):
            return f"`{name}`"
        case BumpParent(parent_name=parent, reason=reason):
            return f"`{_name_of(reason)}` (via `{parent}`)"


def _change_label(action: UpgradeAction) -> str:
    match action:
        case BumpDirect() | BumpParent():
            return f"`{action.from_version}` → `{action.to_version}`"
        case Override(to_version=version):
            return f"pinned to `{version}`"


def _kind_label(action: UpgradeAction) -> str:
    match action:
        case BumpDirect():
            return "direct"
        case BumpParent():
            return "transitive (parent bump)"
        case Override():
            return "transitive (override)"


def _reason_of(action: UpgradeAction) -> str:
    match action:
        case BumpParent(reason=reason) | Override(reason=reason):
            return reason
        case BumpDirect(name=name, from_version=version):
            return f"pkg:npm/{name.replace('@', '%40', 1)}@{version}"


def _name_of(purl: str) -> str:
    try:
        return parse_purl(purl)[1]
    except PurlError:
        return purl  # a malformed purl must not break the body


def _counts(plan: UpgradePlan, severities: dict[str, Severity]) -> dict[Severity, int]:
    counts: dict[Severity, int] = {}
    for action in plan.actions:
        severity = severities.get(_reason_of(action), "unknown")
        counts[severity] = counts.get(severity, 0) + 1
    return counts


def _breakdown(counts: dict[Severity, int]) -> str:
    parts = [
        f"{counts[severity]} {severity}" for severity in _SEVERITY_ORDER if counts.get(severity)
    ]
    return f" ({', '.join(parts)})" if parts else ""


def _not_fixed(plan: UpgradePlan) -> str:
    return "\n".join(
        f"- {item.osv_id}: {_UNRESOLVED_WORDING.get(item.reason, item.reason)}"
        for item in plan.unresolved
    )


def _log(entries: list[str]) -> str:
    if not entries:
        return "_Updated automatically as CI runs._"
    return "\n".join(f"- {entry}" for entry in entries)
